/**
 * Приведение названия компании к виду для показа: организационная форма —
 * общепринятой аббревиатурой, у частника без формы — «ИП».
 *
 * В реестре одна и та же форма записана десятком способов:
 *   «КРЕСТЬЯНСКОЕ (ФЕРМЕРСКОЕ) ХОЗЯЙСТВО "ПАХАРЬ"»          → КФХ "ПАХАРЬ"
 *   «Глава крестьянского (фермерского) хозяйства Унаджев...» → КФХ Унаджев...
 *   «К(Ф)Х "ДЕРКУЛ-С"», «КХ "НАТАША"», «ФХ "БЕРЕГИНЯ"»       → КФХ "..."
 *   «САЛОМАТИН НИКОЛАЙ ВЛАДИМИРОВИЧ»                        → ИП САЛОМАТИН...
 *
 * Меняется только то, что видит пользователь: в базе остаётся исходная строка,
 * по ней идут поиск, группировка и выгрузки.
 *
 * Держать в синхроне с fmtCompany() во frontend/js/app.js.
 */

// Порядок важен: длинные формы проверяются раньше своих же коротких кусков
// («закрытое акционерное общество» до «акционерное общество»).
const FORM_RULES = [
  [/^общество\s+с\s+ограниченной\s+ответственностью/i, 'ООО'],
  [/^публичное\s+акционерное\s+общество/i, 'ПАО'],
  [/^непубличное\s+акционерное\s+общество/i, 'НАО'],
  [/^закрытое\s+акционерное\s+общество/i, 'ЗАО'],
  [/^открытое\s+акционерное\s+общество/i, 'ОАО'],
  [/^акционерное\s+общество/i, 'АО'],
  [/^индивидуальный\s+предприниматель/i, 'ИП'],
  [/^физическое\s+лицо[\s-]*предприниматель/i, 'ИП'],
  [/^флп(?![а-яё])/i, 'ИП'],
  // «Глава КФХ Егупов Ю.А.» — форма уже сокращена, но «Глава» лишняя.
  [/^(?:ип\s+)?глав[аы]\s+(?:к\s*\(\s*ф\s*\)\s*х|кфх|к\s*\/\s*х|кх|фх)(?![а-яё])/i, 'КФХ'],
  [/^(?:ип\s+)?глав[аы]\s+крестьянск(?:ого|их)?\s*(?:\([^)]*\)|фермерск(?:ого|их))?\s*хозяйств[ао]?/i, 'КФХ'],
  [/^крестьянск(?:ое|ого)\s*(?:\([^)]*\)|фермерское)?\s*хозяйств[ао]?/i, 'КФХ'],
  [/^фермерское\s+хозяйство/i, 'КФХ'],
  // [а-яё]* вместо \w*: \w в JS кириллицу не покрывает.
  [/^сельскохозяйственн[а-яё]*\s+производственн[а-яё]*\s+кооператив[а-яё]*/i, 'СПК'],
  [/^к\s*\(\s*ф\s*\)\s*х(?![а-яё])/i, 'КФХ'],
  [/^к\s*\/\s*х(?![а-яё])/i, 'КФХ'],
  [/^кх(?![а-яё])/i, 'КФХ'],
  [/^фх(?![а-яё])/i, 'КФХ'],
];

// Отчества — самый надёжный признак, что это человек, а не название.
const PATRONYMIC_RE = /(ович|овича|евич|евича|ьич|ича|овна|овны|евна|евны|ична|инична)$/i;
// «Иванов И.И.» / «ИВАНОВ И. И.»
const INITIALS_RE = /^[А-ЯЁ][А-ЯЁа-яё-]+\s+[А-ЯЁ]\.\s*[А-ЯЁ]\.?$/;

/** Похоже ли название на ФИО частника (а не на название организации). */
function looksLikePerson(s) {
  if (/["«»()\d]/.test(s)) return false;
  const words = s.split(/\s+/);
  if (words.length === 3 && PATRONYMIC_RE.test(words[2])) return true;
  return INITIALS_RE.test(s);
}

function normalizeCompanyName(name) {
  if (!name) return '';
  const s = String(name).replace(/\s+/g, ' ').trim();
  if (!s) return '';

  for (const [re, abbr] of FORM_RULES) {
    const m = re.exec(s);
    if (!m) continue;
    // Хвост после формы: убираем запятые и лишние пробелы, кавычки оставляем.
    const rest = s.slice(m[0].length).replace(/^[\s,.:-]+/, '');
    return rest ? `${abbr} ${rest}` : abbr;
  }

  return looksLikePerson(s) ? `ИП ${s}` : s;
}

module.exports = { normalizeCompanyName };
