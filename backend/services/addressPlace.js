// Как показывать тип в подписи маркера: «с. Кульбаково», но «ст-ца Отрадная».
const TYPE_LABEL = new Map(Object.entries({
  'г': 'г.', 'с': 'с.', 'п': 'п.', 'д': 'д.', 'х': 'х.', 'сл': 'сл.', 'р-н': 'р-н',
}));

// Токены улицы/дома — на них разбор НП прекращается: дальше «д.» это дом, а не деревня.
const STREET_RE = /^(ул|улица|пер|переулок|пр-кт|пр-т|проспект|просп|ш|шоссе|б-р|бул|бульвар|наб|набережная|пл|площадь|проезд|тракт|линия|аллея|тупик|въезд|съезд|мост|квартал|кв-л)\b/i;
const HOUSE_RE = /^(д|дом|зд|здание|стр|строение|корп|корпус|литер|лит|оф|офис|кв|квартира|помещ|пом|влд|владение|уч|участок|соор|сооружение|бокс|этаж|комн|каб|а\/я)\b/i;
const DISTRICT_RE = /(^|[\s,.])(р-?н|район|м\.?\s?о|г\.?\s?о|у-?с|муниципальн[а-яё]*\s+(округ|район)|городск[а-яё]*\s+округ|сельсовет|наслег)(\s|\.|$)/i;
const SKIP_RE = /^(росси[а-яё]*|рф|ru|\d{3,6}|кадастровый\s+номер.*|индекс.*)$/i;
// «вн.тер.г.» — внутригородская территория (районы Москвы и Петербурга):
// отдельными точками на карте они не нужны, иначе вместо Москвы появляются
// «г. Округ Тверской Вн Тер» и ещё десяток таких же.
const INTRACITY_RE = /вн\.?\s?тер|внутригородск/i;

function norm(s) {
  return String(s == null ? '' : s)
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[«»"'`]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

// Служебные частицы в названиях НП пишутся со строчной: «Ростов-на-Дону»,
// «Комсомольск-на-Амуре». С заглавной они не находятся ни в сиде координат,
// ни в справочнике DaData.
const PARTICLES = new Set(['на', 'в', 'у', 'при', 'под', 'над', 'за', 'из', 'по', 'до', 'им', 'де', 'ла']);

function titleCase(s) {
  const parts = String(s).split(/([\s-]+)/);
  return parts.map((part, i) => {
    if (/^[\s-]+$/.test(part)) return part;
    const lower = part.toLowerCase();
    if (i > 0 && PARTICLES.has(lower)) return lower;
    return part.charAt(0).toUpperCase() + lower.slice(1);
  }).join('');
}

// «Мартыновский р-н» / «р-н Мартыновский» / «БЕЛОВОДСКИЙ м.о.» → «Мартыновский»
function bareName(token, typeRe) {
  const cleaned = String(token)
    .replace(typeRe, ' ')
    .replace(/[.,;]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  return cleaned;
}

// Корень должен стоять в начале слова, иначе «Новомосковский р-н» опознался бы
// как Московская область. Регулярки компилируем один раз: на 600 тыс. адресов
// пересборка (100 корней × токен) занимала больше времени, чем весь остальной разбор.
const REGION_RES = REGIONS.map(([stem, label]) => [new RegExp('(^|[^а-я])' + stem), label]);

function findRegion(tokens) {
  for (const token of tokens) {
    const t = norm(token);
    if (!t || SKIP_RE.test(t)) continue;
    for (const [re, label] of REGION_RES) {
      if (re.test(t)) return label;
    }
  }
  return '';
}

const DISTRICT_WORDS_RE = /(^|[\s,.])(р-?н|район|м\.?\s?о|г\.?\s?о|у-?с|муниципальн[а-яё]*|городск[а-яё]*|округ|сельсовет|наслег)(\s|\.|$)/gi;

const typeOfWord = w => {
  const k = norm(w).replace(/\.+$/, '');
  return SETTLEMENT_TYPES.get(k) || WEAK_TYPES.get(k) || null;
};
const isWeakWord = w => WEAK_TYPES.has(norm(w).replace(/\.+$/, ''));

// Тип и название НП из токена: «с Кульбаково», «С. ГОНЧАРОВО», «Кульбаково с».
// deep=true разрешает искать тип в середине токена («2450 м на юго-запад от село
// Греково-Ульяновка») — это последняя попытка, иначе в НП попадают улицы.
function parseSettlementToken(token, { deep = false } = {}) {
  const raw = String(token).replace(/[;]+/g, ' ').trim();
  if (!raw) return null;
  const words = raw.split(/\s+/);

  // тип впереди («с Кульбаково») или сзади («Кульбаково с»)
  for (const at of ['head', 'tail']) {
    const w = at === 'head' ? words[0] : words[words.length - 1];
    const type = typeOfWord(w);
    if (!type) continue;
    const rest = (at === 'head' ? words.slice(1) : words.slice(0, -1)).join(' ')
      .replace(/^[.\s,-]+|[.\s,]+$/g, '').trim();
    if (!rest || !/[а-яёa-z]/i.test(rest)) continue;
    return { type, name: rest, weak: isWeakWord(w) };
  }

  if (!deep) return null;
  for (let i = 1; i < words.length - 1; i++) {
    const type = typeOfWord(words[i]);
    if (!type) continue;
    const rest = words.slice(i + 1).join(' ').replace(/^[.\s,-]+|[.\s,]+$/g, '').trim();
    if (rest && /[а-яё]/i.test(rest)) return { type, name: rest, weak: isWeakWord(words[i]) };
  }
  return null;
}

/**
 * Возвращает null, если в адресе не нашлось региона или населённого пункта
 * (иностранные адреса — их в реестре сотни — отсекаются именно здесь).
 * `key` — ключ для кеша геокодера и группировки на карте, `query` — строка,
 * которую отдаём геокодеру, `precision` — точность (НП или только район).
 */
function parseAddress(address) {
  if (!address) return null;
  const tokens = String(address).split(',').map(s => s.trim()).filter(Boolean);
  if (!tokens.length) return null;

  const region = findRegion(tokens);
  if (!region) return null;

  let district = '';
  let best = null;      // настоящий НП
  let fallback = null;  // слабый (СНТ, мкр, с/п) — если настоящего нет
  const rest = [];      // токены, в которых НП не нашёлся с первого подхода

  for (const token of tokens) {
    const t = norm(token);
    if (!t || SKIP_RE.test(t) || INTRACITY_RE.test(t)) continue;

    // дошли до улицы или дома — НП уже был бы раньше
    if (STREET_RE.test(t) || HOUSE_RE.test(t)) {
      if (best) break;
      continue;
    }
    if (!district && DISTRICT_RE.test(token)) {
      const name = bareName(token, DISTRICT_WORDS_RE);
      // «Ханты-Мансийский автономный округ» — это регион, а не район; но район
      // «Приморский» в Запорожской области отбрасывать нельзя, хотя корень
      // совпадает с Приморским краем — поэтому сверяем именно с найденным регионом
      if (name && findRegion([name]) !== region) {
        // «Тацинский район х. Зазерский» — район и НП в одном токене без запятой
        const inner = parseSettlementToken(name, { deep: true });
        if (inner) {
          district = titleCase(bareName(name.replace(inner.name, ' '), DISTRICT_WORDS_RE));
          if (!best && !inner.weak) best = inner;
          else if (!fallback) fallback = inner;
        } else {
          district = titleCase(name);
        }
      }
      continue;
    }
    const parsed = parseSettlementToken(token);
    if (!parsed) { rest.push(token); continue; }
    if (parsed.weak) { if (!fallback) fallback = parsed; continue; }
    if (!best) best = parsed;
  }

  // последняя попытка — тип НП в середине токена
  if (!best && !fallback) {
    for (const token of rest) {
      const parsed = parseSettlementToken(token, { deep: true });
      if (parsed) { if (parsed.weak) fallback = parsed; else best = parsed; break; }
    }
  }

  const place = best || fallback;
  // Города федерального значения пишут как регион, отдельного токена НП нет
  const cityRegion = /^г (Москва|Санкт-Петербург|Севастополь|Байконур)$/.exec(region);
  let type = place ? place.type : '';
  let name = place ? titleCase(place.name) : '';
  let precision = 'settlement';

  if (!name && cityRegion) { type = 'г'; name = cityRegion[1]; }
  // НП в адресе нет («РОССИЯ, обл Воронежская, р-н Каширский» или «земли
  // сельскохозяйственного назначения») — ставим точку по центру района
  if (!name && district) { type = 'р-н'; name = district; precision = 'district'; }
  if (!name) return null;

  // Город и его городской округ пишут в двух токенах («город Ростов-на-Дону,
  // г Ростов-на-Дону») — район тогда лишний, иначе на один город два ключа.
  const keyDistrict = (type === 'г' || type === 'р-н' || norm(district) === norm(name)) ? '' : district;
  const key = [norm(region), norm(keyDistrict), type + ' ' + norm(name)].join('|');
  const query = precision === 'district'
    ? [region, name + ' р-н'].join(', ')
    : [region, keyDistrict && keyDistrict + ' р-н', type + ' ' + name].filter(Boolean).join(', ');

  return {
    region, district: keyDistrict, type, name, precision, key, query,
    label: (TYPE_LABEL.get(type) || type) + ' ' + name,
  };
}

module.exports = { parseAddress, norm, REGIONS };
